package com.example.service

import android.content.Context
import android.content.Intent
import android.net.Uri
import java.net.URLEncoder

object WhatsAppHelper {

    enum class MessageType {
        GST_DUE,
        ITR_DUE,
        TDS_DUE,
        DOCUMENT_REQUEST,
        PAYMENT_REMINDER,
        INVOICE_BILL
    }

    fun buildMessage(
        type: MessageType,
        clientName: String,
        returnOrDocType: String,
        period: String,
        dueDate: String,
        amount: Double = 0.0,
        isHindi: Boolean = false
    ): String {
        return if (isHindi) {
            when (type) {
                MessageType.GST_DUE ->
                    "प्रिय $clientName जी,\n\nश्री नव्या लेखा एसोसिएट्स की ओर से सादर प्रणाम।\n\nआपकी $returnOrDocType ($period) की नियत तारीख (Due Date) $dueDate है। कृपया समय पर रिटर्न फाइलिंग हेतु सभी बिल एवं डेटा शीघ्र उपलब्ध कराएं।\n\nधन्यवाद,\nश्री नव्या लेखा एसोसिएट्स\nटैक्स एवं जीएसटी कंसल्टेंट"

                MessageType.ITR_DUE ->
                    "प्रिय $clientName जी,\n\nअसेसमेंट ईयर $period के लिए आपकी आयकर विवरणी ($returnOrDocType) फाइल करने की अंतिम तिथि $dueDate है। पेनल्टी से बचने हेतु कृपया अपनी बैंक स्टेटमेंट, फॉर्म 26AS/AIS एवं आय विवरण प्रदान करें।\n\nसादर,\nश्री नव्या लेखा एसोसिएट्स"

                MessageType.TDS_DUE ->
                    "प्रिय $clientName जी,\n\nतिमाही $period के टीडीएस रिटर्न ($returnOrDocType) की देय तिथि $dueDate है। कृपया सभी चालान एवं कटौती विवरण हमें भेजें।\n\nसादर,\nश्री नव्या लेखा एसोसिएट्स"

                MessageType.DOCUMENT_REQUEST ->
                    "प्रिय $clientName जी,\n\nआपके टैक्स कम्प्लायंस ($returnOrDocType) के लिए आवश्यक दस्तावेज (बैलेंस शीट, बैंक विवरण आदि) प्रतीक्षित हैं। कृपया इन्हें शीघ्र भेजने का कष्ट करें।\n\nसादर,\nश्री नव्या लेखा एसोसिएट्स"

                MessageType.PAYMENT_REMINDER ->
                    "प्रिय $clientName जी,\n\nश्री नव्या लेखा एसोसिएट्स की टैक्स परामर्श एवं फाइलिंग फीस का बकाया ₹${"%,.2f".format(amount)} नियत तिथि $dueDate तक देय है। कृपया यूपीआई/बैंक ट्रांसफर द्वारा भुगतान करें।\n\nसादर,\nश्री नव्या लेखा एसोसिएट्स"

                MessageType.INVOICE_BILL ->
                    "प्रिय $clientName जी,\n\nआपके $returnOrDocType का टैक्स इनवॉइस संलग्न/जनरेट किया गया है। कुल देय राशि ₹${"%,.2f".format(amount)} है।\n\nसादर,\nश्री नव्या लेखा एसोसिएट्स"
            }
        } else {
            when (type) {
                MessageType.GST_DUE ->
                    "Dear $clientName,\n\nGreetings from Shree Navya Lekha Associates.\n\nYour $returnOrDocType for tax period $period is due on $dueDate.\n\nPlease provide the required sales, purchase books, and data to Shree Navya Lekha Associates for timely filing without late fees.\n\nRegards,\nShree Navya Lekha Associates\nTax & Compliance Advisors"

                MessageType.ITR_DUE ->
                    "Dear $clientName,\n\nThis is a reminder that your Income Tax Return ($returnOrDocType) for $period is due on $dueDate.\n\nPlease share your Bank Statements, Form 26AS/AIS, and investment proofs at the earliest.\n\nRegards,\nShree Navya Lekha Associates"

                MessageType.TDS_DUE ->
                    "Dear $clientName,\n\nYour TDS / TCS quarterly return ($returnOrDocType) for $period is due on $dueDate.\n\nKindly share all tax deduction details and paid challans.\n\nRegards,\nShree Navya Lekha Associates"

                MessageType.DOCUMENT_REQUEST ->
                    "Dear $clientName,\n\nDocuments required for your $returnOrDocType compliance are currently awaited. Please forward them to Shree Navya Lekha Associates.\n\nRegards,\nShree Navya Lekha Associates"

                MessageType.PAYMENT_REMINDER ->
                    "Dear $clientName,\n\nThis is a gentle reminder regarding the outstanding professional fees of ₹${"%,.2f".format(amount)} due on $dueDate for taxation and filing services.\n\nKindly clear via UPI or Bank Transfer.\n\nRegards,\nShree Navya Lekha Associates"

                MessageType.INVOICE_BILL ->
                    "Dear $clientName,\n\nInvoice for professional taxation services ($returnOrDocType) of ₹${"%,.2f".format(amount)} has been generated by Shree Navya Lekha Associates.\n\nRegards,\nShree Navya Lekha Associates"
            }
        }
    }

    fun openWhatsApp(context: Context, mobileNumber: String, message: String) {
        val cleanNumber = mobileNumber.replace("[^0-9]".toRegex(), "")
        val formattedNumber = if (cleanNumber.length == 10) "91$cleanNumber" else cleanNumber
        val encodedMessage = URLEncoder.encode(message, "UTF-8")
        val uri = Uri.parse("https://api.whatsapp.com/send?phone=$formattedNumber&text=$encodedMessage")
        val intent = Intent(Intent.ACTION_VIEW, uri).apply {
            flags = Intent.FLAG_ACTIVITY_NEW_TASK
        }
        try {
            context.startActivity(intent)
        } catch (e: Exception) {
            // Fallback to generic chooser
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                putExtra(Intent.EXTRA_TEXT, message)
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            context.startActivity(Intent.createChooser(shareIntent, "Share Reminder"))
        }
    }

    fun sendSms(context: Context, mobileNumber: String, message: String) {
        val uri = Uri.parse("smsto:$mobileNumber")
        val intent = Intent(Intent.ACTION_SENDTO, uri).apply {
            putExtra("sms_body", message)
            flags = Intent.FLAG_ACTIVITY_NEW_TASK
        }
        try {
            context.startActivity(intent)
        } catch (ignored: Exception) {}
    }

    fun sendEmail(context: Context, emailAddress: String, subject: String, body: String) {
        val intent = Intent(Intent.ACTION_SENDTO).apply {
            data = Uri.parse("mailto:")
            putExtra(Intent.EXTRA_EMAIL, arrayOf(emailAddress))
            putExtra(Intent.EXTRA_SUBJECT, subject)
            putExtra(Intent.EXTRA_TEXT, body)
            flags = Intent.FLAG_ACTIVITY_NEW_TASK
        }
        try {
            context.startActivity(intent)
        } catch (ignored: Exception) {}
    }
}
